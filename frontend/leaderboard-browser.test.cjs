'use strict';
const assert=require('node:assert/strict');
const {chromium}=require(process.env.BENCHSQUARE_PLAYWRIGHT||'playwright');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const base=process.env.DEMO_BASE||'http://127.0.0.1:4173/frontend/';
    await page.goto(base+'#competition/mine-example-active');
    await page.getByRole('tab',{name:'排行榜',exact:true}).click();
    await page.locator('.lb-table').waitFor();
    assert.equal(await page.locator('.lb-table tbody tr').count(),10);
    assert.equal(await page.locator('.lb-table tbody tr').nth(0).locator('.lb-number').last().innerText(),'1');
    assert.equal(await page.locator('.lb-table tbody tr').nth(1).locator('.lb-number').last().innerText(),'2');
    assert.deepEqual(await page.locator('.lb-rank').allTextContents(),['1','2','2','4','5','6','7','8','9','10']);
    assert.equal(await page.locator('.lb-mine').count(),1);
    assert.equal(await page.locator('.detail-aside').isVisible(),false);
    assert.equal(await page.locator('[data-lb="toggle"]').getAttribute('aria-expanded'),'false');
    assert.equal(await page.getByRole('button',{name:/上一页|下一页/}).count(),0);
    const scores=await page.locator('.lb-score').allTextContents();
    await page.getByRole('button',{name:'更新排行榜'}).click();
    assert.deepEqual(await page.locator('.lb-score').allTextContents(),scores);
    await page.locator('#toast:not(.show)').waitFor({state:'attached'});
    await page.screenshot({path:'frontend/leaderboard-desktop-preview.png',fullPage:true});
    assert.equal(await page.locator('.lb-controls, #lb-search, #lb-only-mine').count(),0);
    await page.locator('#lb-scenario').selectOption('unscored');
    assert.equal(await page.locator('.lb-table tbody tr').count(),10);
    assert.ok((await page.locator('.lb-own-notice').innerText()).includes('我的团队暂无成绩'));
    await page.locator('[data-lb="toggle"]').click();
    assert.equal(await page.locator('.lb-rank').count(),20);
    assert.equal(await page.locator('.lb-rank').nth(10).innerText(),'11');
    assert.equal(await page.locator('[data-lb="toggle"]').getAttribute('aria-expanded'),'true');
    await page.getByRole('button',{name:'更新排行榜'}).click();
    assert.equal(await page.locator('.lb-rank').count(),20,'update preserves expanded state');
    await page.locator('#toast:not(.show)').waitFor({state:'attached'});
    await page.screenshot({path:'frontend/leaderboard-expanded-preview.png',fullPage:true});
    await page.locator('[data-lb="toggle"]').press('Enter');
    assert.equal(await page.locator('.lb-rank').count(),10);
    assert.equal(await page.locator('[data-lb="toggle"]').getAttribute('aria-expanded'),'false');
    await page.locator('#lb-scenario').selectOption('empty');
    assert.equal(await page.locator('.lb-empty h3').innerText(),'成绩尚未公布');
    assert.equal(await page.locator('.lb-fold-control').count(),0);
    await page.screenshot({path:'frontend/leaderboard-empty-preview.png',fullPage:true});
    await page.locator('#lb-scenario').selectOption('scores');
    await page.getByRole('tab',{name:'概览',exact:true}).click();
    assert.equal(await page.locator('.detail-aside').isVisible(),true);
    await page.getByRole('tab',{name:'排行榜',exact:true}).click();
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right<=1);
    await page.evaluate(()=>window.scrollTo(0,0));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.screenshot({path:'frontend/leaderboard-mobile-preview.png',fullPage:true});
    await page.goto(base+'#competition/code');
    await page.getByRole('tab',{name:'排行榜',exact:true}).click();
    assert.equal(await page.locator('.lb-controls, #lb-search, #lb-only-mine').count(),0);
    assert.deepEqual(errors,[]);
    console.log('Leaderboard UI passed: top-ten folding, expand/collapse by keyboard, expanded refresh, removed filters, global ties, own team notice, empty state, tab layout and mobile overflow.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
